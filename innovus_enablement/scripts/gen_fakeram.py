#!/usr/bin/env python3
"""Generate abstract single-port SRAM ("fakeram") macros for i3dPDK_A16K.

    gen_fakeram.py 256x32 [64x32 ...] [--name-prefix fakeram7_] [--scale 4]

Writes, per macro <prefix><words>x<bits>:
  innovus_enablement/macros/<name>.lib              timing/power (scalar NLDM, TT 0.7V 27C)
  innovus_enablement/lef[_x<N>]/<name>.lef          CLASS BLOCK abstract (read after tech LEF)

The pin interface matches OpenROAD-flow-scripts' bsg_fakeram macros
(clk, ce_in, we_in, addr_in[], wd_in[], [w_mask_in[] with --wmask], rd_out[]), so ORFS RTL that
instantiates fakeram7_*/fakeram45_* works unchanged when --name-prefix is set
to match. Everything else is an ASSUMPTION for a 16A-class node, not PDK data:
  - area = bits * BITCELL_UM2 * PERIPHERY_OVERHEAD (optimistic CFET SRAM projection)
  - signal pins one per M4 track on the left edge (height is pin-limited for
    wide words: n_pins * PIN_PITCH)
  - timing/power from the simple formulas in write_lib()
There is no layout: the merged GDS will not contain these cells.

Another PDK (plugged in as a sibling checkout, see pnr/flow.tcl) gives its
geometry with --site-w/--row-lcm/--m4-pitch/--m4-width/--no-bpr and its
innovus_enablement/ with --out (macros/, lef[_x<N>]/ are written there).
"""
import argparse
import math
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "innovus_enablement")

BITCELL_UM2 = 0.005          # optimistic CFET SRAM projection (~1/4 of the N2 HD bitcell, 0.021); --bitcell
PERIPHERY_OVERHEAD = 1.10    # decoders, sense amps, IO (~91% array efficiency; --overhead)
SITE_W = 0.042               # CPP; macro width snaps to it
ROW_LCM = 1.08               # lcm of 3T/4T/5T row heights (0.054/0.072/0.090)
M4_PITCH, M4_W = 0.060, 0.030
PIN_PITCH = M4_PITCH         # one signal pin per M4 track (0.03 gap = M4 min spacing); --pin-tracks
PIN_LEN = 0.24
PG_W, PG_PITCH = 0.12, 1.0   # M5 PG straps (--pg-layer / --pg-dir / --pg-pitch / --pg-width)
PG_LAYER, PG_HORIZ = "M5", False
EDGE = 0.24                  # keep-out from macro corners for pins/straps
GRID = 0.0005                # tech LEF manufacturing grid (1x)
WMASK = False                # --wmask: add w_mask_in[bits] (bsg_fakeram45 style)
OBS_LAYERS = ("BPR", "M0", "M1", "M2", "M3")
OBS_CUTS = ("BPR2TOP", "VIA0", "VIA1", "VIA2", "VIA3")


def snap_up(v, g):
    return math.ceil(v / g - 1e-9) * g


def geometry(words, bits, aspect):
    n_sig = 3 + math.ceil(math.log2(words)) + (3 if WMASK else 2) * bits
    area = words * bits * BITCELL_UM2 * PERIPHERY_OVERHEAD
    h = max(math.sqrt(area * aspect), n_sig * PIN_PITCH + 2 * EDGE)
    h = snap_up(h, ROW_LCM)
    w = snap_up(area / h, SITE_W)
    # room for two vertical straps (the default pitch 1.0 also for horizontal ones, so both have one size)
    w = max(w, snap_up(PIN_LEN + 2 * EDGE + 2 * (1.0 if PG_HORIZ else PG_PITCH), SITE_W))
    return w, h


def pins(words, bits):
    abits = math.ceil(math.log2(words))
    sig = ["clk", "ce_in", "we_in"]
    sig += [f"addr_in[{i}]" for i in range(abits)]
    sig += [f"wd_in[{i}]" for i in range(bits)]
    if WMASK:
        sig += [f"w_mask_in[{i}]" for i in range(bits)]
    sig += [f"rd_out[{i}]" for i in range(bits)]
    return abits, sig


def f(v, s):
    return f"{v * s:.4f}"


def write_lef(path, name, words, bits, w, h, s):
    abits, sig = pins(words, bits)
    o = [f"# Generated by innovus_enablement/scripts/gen_fakeram.py: abstract {words}x{bits} SRAM.",
         "# Geometry is an assumption (see script header), not PDK data.",
         "VERSION 5.8 ;", 'BUSBITCHARS "[]" ;', 'DIVIDERCHAR "/" ;', "",
         f"MACRO {name}", "  CLASS BLOCK ;", f"  FOREIGN {name} 0 0 ;", "  ORIGIN 0 0 ;",
         f"  SIZE {f(w, s)} BY {f(h, s)} ;", "  SYMMETRY X Y R90 ;"]
    # Signal pins: M4 stubs on the left edge, centred vertically.
    span = (len(sig) - 1) * PIN_PITCH
    # centred on M4 tracks (tech LEF OFFSET = pitch/2)
    y0 = snap_up((h - span) / 2, M4_PITCH) + M4_PITCH / 2
    for i, p in enumerate(sig):
        yc = y0 + i * PIN_PITCH
        d = "OUTPUT" if p.startswith("rd_out") else "INPUT"
        use = "CLOCK" if p == "clk" else "SIGNAL"
        o += [f"  PIN {p}", f"    DIRECTION {d} ;", f"    USE {use} ;", "    PORT",
              "      LAYER M4 ;",
              f"        RECT 0 {f(yc - M4_W / 2, s)} {f(PIN_LEN, s)} {f(yc + M4_W / 2, s)} ;",
              "    END", f"  END {p}"]
    # PG pins: straps over the array, alternating VDD/VSS: vertical on M5 (default), or with
    # --pg-dir horizontal full-width straps on --pg-layer, centred like the signal pins half an M4
    # pitch off the M4 grid, so that the macro (snapped to the M4 grid, either y orientation) puts
    # them on the tracks of a layer of twice the M4 pitch after at most one M4 pitch of shift
    # (i3dPDK_NS3K: M6, pitch 0.048 = 2 x M4; see pnr/flow.tcl).
    xs = []
    if PG_HORIZ:
        x = snap_up(EDGE + PG_W / 2 - M4_PITCH / 2, M4_PITCH) + M4_PITCH / 2
        while x + PG_W / 2 <= h - EDGE:
            xs.append(x)
            x += PG_PITCH
    else:
        x = PIN_LEN + EDGE + PG_PITCH / 2
        while x + PG_W / 2 <= w - EDGE:
            xs.append(x)
            x += PG_PITCH
    if len(xs) < 2:
        raise SystemExit(f"{name}: too narrow for PG straps")
    for net, use in (("VDD", "POWER"), ("VSS", "GROUND")):
        o += [f"  PIN {net}", "    DIRECTION INOUT ;", f"    USE {use} ;", "    PORT", f"      LAYER {PG_LAYER} ;"]
        for k, xc in enumerate(xs):
            if (k % 2 == 0) == (net == "VDD"):
                if PG_HORIZ:
                    o.append(f"        RECT 0 {f(xc - PG_W / 2, s)} {f(w, s)} {f(xc + PG_W / 2, s)} ;")
                else:
                    o.append(f"        RECT {f(xc - PG_W / 2, s)} 0 {f(xc + PG_W / 2, s)} {f(h, s)} ;")
        o += ["    END", f"  END {net}"]
    # Obstructions: everything below M4, and M4 except the pin strip.
    o.append("  OBS")
    for lay in OBS_LAYERS:
        o += [f"    LAYER {lay} ;", f"      RECT 0 0 {f(w, s)} {f(h, s)} ;"]
    for cut in OBS_CUTS:
        o += [f"    LAYER {cut} ;", f"      RECT 0 0 {f(w, s)} {f(h, s)} ;"]
    o += ["    LAYER M4 ;", f"      RECT {f(PIN_LEN + M4_PITCH, s)} 0 {f(w, s)} {f(h, s)} ;"]
    o += ["  END", f"END {name}", "", "END LIBRARY"]
    with open(path, "w") as fh:
        fh.write("\n".join(o) + "\n")
    return len(xs)


def write_lib(path, name, words, bits, w, h):
    abits, _ = pins(words, bits)
    kbits = words * bits / 1024
    # Simple scaling: access grows with log2(words) (decode) and bits (wordline).
    t_acc = 0.060 + 0.010 * math.log2(words) + 0.0008 * bits
    t_setup, t_hold, t_out = 0.030, 0.010, 0.020
    c_in, c_clk = 0.6, 2.0 + 0.02 * bits          # fF
    e_read = 40 * kbits + 2 * bits                   # fJ per access
    leak = 60.0 * words * bits                       # pW
    lib = f"library({name}) {{"
    L = [f"/* Generated by innovus_enablement/scripts/gen_fakeram.py: abstract {words}x{bits} SRAM.",
         "   Timing/power are ASSUMPTIONS for a 16A-class node, not PDK data. */",
         lib,
         "  technology (cmos) ;", "  delay_model : table_lookup ;",
         '  time_unit : "1ns" ;', '  voltage_unit : "1V" ;', '  current_unit : "1mA" ;',
         '  leakage_power_unit : "1pW" ;', '  pulling_resistance_unit : "1kohm" ;',
         "  capacitive_load_unit (1, ff) ;",
         "  nom_process : 1 ;", "  nom_voltage : 0.7 ;", "  nom_temperature : 27 ;",
         "  operating_conditions (TYPICAL) { process : 1 ; voltage : 0.7 ; temperature : 27 ; }",
         "  default_operating_conditions : TYPICAL ;",
         "  input_threshold_pct_rise : 50 ;", "  input_threshold_pct_fall : 50 ;",
         "  output_threshold_pct_rise : 50 ;", "  output_threshold_pct_fall : 50 ;",
         "  slew_lower_threshold_pct_rise : 20 ;", "  slew_upper_threshold_pct_rise : 80 ;",
         "  slew_lower_threshold_pct_fall : 20 ;", "  slew_upper_threshold_pct_fall : 80 ;",
         "  default_max_transition : 0.2 ;",
         f"  type (addr_t) {{ base_type : array ; data_type : bit ; bit_width : {abits} ; "
         f"bit_from : {abits - 1} ; bit_to : 0 ; downto : true ; }}",
         f"  type (data_t) {{ base_type : array ; data_type : bit ; bit_width : {bits} ; "
         f"bit_from : {bits - 1} ; bit_to : 0 ; downto : true ; }}",
         f"  cell ({name}) {{",
         f"    area : {w * h:.4f} ;", "    interface_timing : true ;",
         "    dont_use : true ;", "    dont_touch : true ;", "    is_macro_cell : true ;",
         f"    cell_leakage_power : {leak:.1f} ;",
         "    pin (clk) {", "      direction : input ;", f"      capacitance : {c_clk:.3f} ;",
         "      clock : true ;", "      min_pulse_width_high : 0.05 ;", "      min_pulse_width_low : 0.05 ;",
         "      internal_power () {",
         f"        rise_power (scalar) {{ values (\"{e_read:.1f}\") ; }}",
         "        fall_power (scalar) { values (\"0.0\") ; }", "      }", "    }"]

    def constrained(p, bus=None):
        head = f"    bus ({p}) {{ bus_type : {bus} ;" if bus else f"    pin ({p}) {{"
        return [head, "      direction : input ;", f"      capacitance : {c_in:.3f} ;",
                "      timing () { related_pin : \"clk\" ; timing_type : setup_rising ;",
                f"        rise_constraint (scalar) {{ values (\"{t_setup}\") ; }}",
                f"        fall_constraint (scalar) {{ values (\"{t_setup}\") ; }} }}",
                "      timing () { related_pin : \"clk\" ; timing_type : hold_rising ;",
                f"        rise_constraint (scalar) {{ values (\"{t_hold}\") ; }}",
                f"        fall_constraint (scalar) {{ values (\"{t_hold}\") ; }} }}",
                "    }"]

    L += constrained("ce_in") + constrained("we_in")
    L += constrained("addr_in", "addr_t") + constrained("wd_in", "data_t")
    if WMASK:
        L += constrained("w_mask_in", "data_t")
    L += ["    bus (rd_out) { bus_type : data_t ;", "      direction : output ;",
          "      max_capacitance : 20.0 ;",
          "      timing () { related_pin : \"clk\" ; timing_type : rising_edge ; timing_sense : non_unate ;",
          f"        cell_rise (scalar) {{ values (\"{t_acc:.4f}\") ; }}",
          f"        cell_fall (scalar) {{ values (\"{t_acc:.4f}\") ; }}",
          f"        rise_transition (scalar) {{ values (\"{t_out}\") ; }}",
          f"        fall_transition (scalar) {{ values (\"{t_out}\") ; }} }}",
          "    }", "  }", "}"]
    with open(path, "w") as fh:
        fh.write("\n".join(L) + "\n")
    return t_acc


def main():
    global PERIPHERY_OVERHEAD, BITCELL_UM2, WMASK, PIN_PITCH, SITE_W, ROW_LCM, M4_PITCH, M4_W
    global OBS_LAYERS, OBS_CUTS, OUT, PG_W, PG_PITCH, PG_LAYER, PG_HORIZ
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("sizes", nargs="+", help="<words>x<bits>, e.g. 256x32")
    ap.add_argument("--name-prefix", default="fakeram7_",
                    help="cell name prefix; match the RTL (default fakeram7_, as in ORFS riscv32i)")
    ap.add_argument("--scale", type=int, nargs="+", default=[1, 4],
                    help="LEF geometry scales to write (default 1 4)")
    ap.add_argument("--aspect", type=float, default=2.0, help="target height/width")
    ap.add_argument("--wmask", action="store_true",
                    help="add a per-bit write mask w_mask_in[bits-1:0] (bsg_fakeram45 / ORFS nangate45 macros)")
    ap.add_argument("--bitcell", type=float, default=BITCELL_UM2,
                    help="bitcell area in um2 (default %(default)s)")
    ap.add_argument("--overhead", type=float, default=PERIPHERY_OVERHEAD,
                    help="macro area / bitcell array area (default %(default)s)")
    ap.add_argument("--pin-tracks", type=int, default=1,
                    help="M4 tracks per signal pin on the macro edge (default 1; 2 = the old spacing)")
    # Geometry of another PDK (defaults: i3dPDK_A16K)
    ap.add_argument("--site-w", type=float, default=SITE_W, help="CPP; macro width snaps to it")
    ap.add_argument("--row-lcm", type=float, default=ROW_LCM,
                    help="macro height snaps to it (whole rows, keeping the row parity)")
    ap.add_argument("--m4-pitch", type=float, default=M4_PITCH)
    ap.add_argument("--m4-width", type=float, default=M4_W)
    ap.add_argument("--no-bpr", action="store_true", help="no BPR/BPR2TOP obstruction layers")
    ap.add_argument("--obs-layers", nargs="+",
                    help="routing layers below M4 to obstruct (default: BPR M0 M1 M2 M3)")
    ap.add_argument("--obs-cuts", nargs="+",
                    help="cut layers below M4 to obstruct (default: BPR2TOP VIA0 VIA1 VIA2 VIA3)")
    ap.add_argument("--pg-layer", default=PG_LAYER, help="layer of the PG straps (default %(default)s)")
    ap.add_argument("--pg-dir", choices=["vertical", "horizontal"], default="vertical",
                    help="PG strap direction; horizontal: full-width straps centred half an M4 pitch off the M4 grid")
    ap.add_argument("--pg-pitch", type=float, default=PG_PITCH, help="PG strap pitch, 1x um (default %(default)s)")
    ap.add_argument("--pg-width", type=float, default=PG_W, help="PG strap width, 1x um (default %(default)s)")
    ap.add_argument("--out", default=OUT, help="innovus_enablement/ dir to write macros/, lef*/ in")
    args = ap.parse_args()
    SITE_W, ROW_LCM, M4_PITCH, M4_W, OUT = args.site_w, args.row_lcm, args.m4_pitch, args.m4_width, args.out
    if args.no_bpr:
        OBS_LAYERS = tuple(l for l in OBS_LAYERS if l != "BPR")
        OBS_CUTS = tuple(c for c in OBS_CUTS if c != "BPR2TOP")
    if args.obs_layers:
        OBS_LAYERS = tuple(args.obs_layers)
    if args.obs_cuts:
        OBS_CUTS = tuple(args.obs_cuts)
    PIN_PITCH = args.pin_tracks * M4_PITCH
    PG_W, PG_PITCH, PG_LAYER, PG_HORIZ = args.pg_width, args.pg_pitch, args.pg_layer, args.pg_dir == "horizontal"
    libdir = os.path.join(OUT, "macros")
    os.makedirs(libdir, exist_ok=True)
    for sz in args.sizes:
        words, bits = map(int, sz.lower().split("x"))
        name = f"{args.name_prefix}{words}x{bits}"
        PERIPHERY_OVERHEAD = args.overhead
        WMASK = args.wmask
        BITCELL_UM2 = args.bitcell
        w, h = geometry(words, bits, args.aspect)
        t = write_lib(os.path.join(libdir, f"{name}.lib"), name, words, bits, w, h)
        for s in args.scale:
            d = os.path.join(OUT, "lef" if s == 1 else f"lef_x{s}")
            os.makedirs(d, exist_ok=True)
            n = write_lef(os.path.join(d, f"{name}.lef"), name, words, bits, w, h, s)
        print(f"{name}: {w:.3f} x {h:.3f} um (1x), {w * h:.1f} um2, "
              f"{n} PG straps, t_acc {t:.3f} ns")


if __name__ == "__main__":
    main()
